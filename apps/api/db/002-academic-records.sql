-- Apply once after 001-auth.sql. No graduation rules are defined here.
BEGIN;

CREATE TABLE departments (
  department_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_code text UNIQUE,
  department_name text NOT NULL CHECK (btrim(department_name) <> '')
);

CREATE TABLE student_profiles (
  user_id uuid PRIMARY KEY REFERENCES app_users(id) ON DELETE CASCADE,
  department_id integer NOT NULL REFERENCES departments(department_id),
  student_no text NOT NULL UNIQUE CHECK (btrim(student_no) <> ''),
  admission_year integer NOT NULL CHECK (admission_year BETWEEN 1900 AND 9999),
  volunteer_hours numeric(6,1) CHECK (volunteer_hours BETWEEN 0 AND 99999.9),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE semesters (
  semester_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  year integer NOT NULL CHECK (year BETWEEN 1900 AND 9999),
  -- Preserve official codes (e.g. 10, 20); do not infer seasonal term codes.
  term_code text NOT NULL CHECK (btrim(term_code) <> ''),
  UNIQUE (year, term_code)
);

CREATE TABLE student_language_scores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  exam_type text NOT NULL CHECK (btrim(exam_type) <> ''),
  score numeric CHECK (score >= 0 AND score < 'Infinity'::numeric),
  grade text CHECK (btrim(grade) <> ''),
  taken_at date,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (score IS NOT NULL OR grade IS NOT NULL)
);

CREATE INDEX student_language_scores_user_idx ON student_language_scores(user_id);

CREATE TABLE courses (
  course_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_number text NOT NULL UNIQUE CHECK (btrim(course_number) <> ''),
  course_name text NOT NULL CHECK (btrim(course_name) <> ''),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE course_sections (
  section_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id integer NOT NULL REFERENCES courses(course_id),
  semester_id integer NOT NULL REFERENCES semesters(semester_id),
  section_number text NOT NULL CHECK (btrim(section_number) <> ''),
  department_id integer REFERENCES departments(department_id),
  course_name_snapshot text NOT NULL CHECK (btrim(course_name_snapshot) <> ''),
  credits numeric(4,1) NOT NULL CHECK (credits BETWEEN 0 AND 999.9),
  category_code text,
  category_name text,
  recommended_year text,
  professor_name text,
  schedule_text text,
  synced_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (semester_id, course_id, section_number),
  UNIQUE (section_id, course_id, semester_id)
);
CREATE INDEX course_sections_course_idx ON course_sections(course_id);
CREATE INDEX course_sections_department_idx ON course_sections(department_id);

CREATE TABLE academic_imports (
  import_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  batch_id uuid NOT NULL,
  document_type text NOT NULL CHECK (document_type IN ('transcript', 'enrollment_confirmation')),
  file_name text NOT NULL CHECK (btrim(file_name) <> ''),
  file_hash text NOT NULL CHECK (file_hash ~ '^[0-9a-f]{64}$'),
  parser_version text NOT NULL CHECK (btrim(parser_version) <> ''),
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'parsed', 'committed', 'failed')),
  error_details jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  committed_at timestamptz,
  CHECK ((status = 'committed') = (committed_at IS NOT NULL)),
  UNIQUE (user_id, batch_id, document_type),
  UNIQUE (import_id, user_id)
);
-- Hash is deliberately not unique: explicit reprocessing must remain possible.
CREATE INDEX academic_imports_file_idx ON academic_imports(user_id, document_type, file_hash);

CREATE TABLE student_course_records (
  record_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  semester_id integer NOT NULL REFERENCES semesters(semester_id),
  course_id integer REFERENCES courses(course_id),
  section_id integer,
  match_status text NOT NULL DEFAULT 'unmatched'
    CHECK (match_status IN ('matched', 'course_only', 'unmatched', 'ambiguous')),
  course_number_snapshot text NOT NULL CHECK (btrim(course_number_snapshot) <> ''),
  course_name_snapshot text NOT NULL CHECK (btrim(course_name_snapshot) <> ''),
  section_number_snapshot text CHECK (btrim(section_number_snapshot) <> ''),
  credits numeric(4,1) NOT NULL CHECK (credits BETWEEN 0 AND 999.9),
  category_snapshot text,
  grade text,
  grade_point numeric(3,2) CHECK (grade_point BETWEEN 0 AND 9.99),
  status text NOT NULL CHECK (status IN ('completed', 'enrolled', 'withdrawn')),
  source_import_id bigint NOT NULL,
  source_row text NOT NULL CHECK (btrim(source_row) <> ''),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  retake boolean,
  retake_reference text,
  FOREIGN KEY (section_id, course_id, semester_id)
    REFERENCES course_sections(section_id, course_id, semester_id),
  FOREIGN KEY (source_import_id, user_id)
    REFERENCES academic_imports(import_id, user_id),
  CHECK (
    (match_status = 'matched' AND course_id IS NOT NULL AND section_id IS NOT NULL)
    OR (match_status = 'course_only' AND course_id IS NOT NULL AND section_id IS NULL)
    OR (match_status IN ('unmatched', 'ambiguous') AND course_id IS NULL AND section_id IS NULL)
  ),
  -- Repeated imports update a record; retakes in another semester remain separate.
  UNIQUE (user_id, semester_id, course_number_snapshot)
);
CREATE INDEX student_course_records_course_idx ON student_course_records(course_id);
CREATE INDEX student_course_records_section_idx ON student_course_records(section_id);
CREATE INDEX student_course_records_import_idx ON student_course_records(source_import_id, user_id);

-- Services must update updated_at explicitly when modifying existing rows.
COMMIT;
